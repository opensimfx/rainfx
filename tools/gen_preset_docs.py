"""Regenerates docs/PRESETS.md from rainfx/data/presets.json + physics (single source of truth).
Run: python tools/gen_preset_docs.py"""
import sys
from pathlib import Path
root = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(root))
from rainfx.core.presets import load_file, derive
from rainfx.core import physics as P

ps = load_file(root / "rainfx" / "data" / "presets.json")
rows = []
for p in ps:
    d = derive(p)
    if p.mode == "dew":
        rows.append(f"| {p.name} | dew | - | {p.d_min_mm}-{p.d_max_mm} | - | - | - | {p.dew_density_m2:.0f} beads/m2 | - |")
        continue
    rate = f"{p.rate_mm_h:g}" if p.mode == "rain" else "-"
    rows.append(f"| {p.name} | {p.mode} | {rate} | {p.d_min_mm:g}-{p.d_max_mm:g} | {d['vt_mean_ms']:.1f} | {p.wind_ms:g} | {d['tilt_deg']:.0f} | {d['count']:,} | "
                f"{(format(d['density_ratio'], '.2%') if 'density_ratio' in d else '-')} |")
table = "\n".join(rows)

vt_rows = "\n".join(f"| {d:g} | {P.rain_terminal_velocity(d):.2f} |" for d in (0.1, 0.2, 0.5, 1, 2, 3, 4, 5, 5.8))
hail_rows = "\n".join(f"| {d} | {P.hail_terminal_velocity(d*10):.1f} |" for d in (0.5, 1, 2, 2.5, 4, 5, 8))

doc = f"""# Presets

Generated by `tools/gen_preset_docs.py` from `rainfx/data/presets.json`. Do not edit the tables by hand.

## Built-in presets (default volume 16 x 16 x 10 m, quality 1.0)

| Preset | Mode | Rain rate (mm/h) | Diameter (mm) | Mean fall speed (m/s) | Wind (m/s) | Streak tilt (deg) | Simulated particles | Simulated / physical |
|---|---|---|---|---|---|---|---|---|
{table}

Rain categories follow the WMO scheme: light up to 2.5 mm/h, moderate 2.5-7.5, heavy 7.6-50, violent above 50.
Agencies differ slightly (UK Met style thresholds are not identical); the table is a starting point, not a standard.

"Simulated / physical" shows how sparse the simulation is compared with the Marshall-Palmer drop concentration in the
same volume. Rain is intentionally under-populated (roughly 0.3-1.3 % of physical in the built-in presets) and compensated visually by streak length
and drop size (`visual_scale`). See PHYSICS.md section 5.

## Reference values used by the formulas

Raindrop terminal velocity (`physics.rain_terminal_velocity`, Gunn-Kinzer / Atlas fit):

| Diameter (mm) | Speed (m/s) |
|---|---|
{vt_rows}

Hail terminal velocity (`physics.hail_terminal_velocity`, 0.85 x 9 D^0.8):

| Diameter (cm) | Speed (m/s) |
|---|---|
{hail_rows}

## Preset file format

Built-in presets live in `rainfx/data/presets.json`. User presets: any `*.json` file in the user presets folder
(shown in the add-on preferences) with the same schema; an entry with an existing `id` overrides the built-in one, a new
`id` appears in the dropdown. A broken file is skipped with a console message; it never blocks the add-on.

```json
{{
  "schema": 1,
  "presets": [
    {{
      "id": "my_monsoon",
      "name": "My Monsoon",
      "category": "rain",
      "mode": "rain",
      "rate_mm_h": 35,
      "d_min_mm": 0.5,
      "d_max_mm": 5.0,
      "visual_density": 36,
      "wind_ms": 11,
      "wind_dir_deg": 80,
      "gust_strength": 4,
      "splash_amount": 3,
      "fog_density": 0.02
    }}
  ]
}}
```

Only `id` and `name` are required; every other field has the default shown in `core/presets.py`.

### Field reference

| Group | Field | Unit | Meaning |
|---|---|---|---|
| identity | `id`, `name`, `category` (`rain`/`frozen`/`surface`), `mode` (`rain`/`hail`/`snow`/`dew`), `description` | | UI grouping and which formulas run |
| population | `rate_mm_h` | mm/h | Sets the Marshall-Palmer slope for rain: lambda = 4.1 R^-0.21 |
| | `d_min_mm`, `d_max_mm` | mm | Truncation range of the diameter distribution |
| | `lam_override` | 1/mm | Fixed exponential slope (hail, snow); 0 = derive from rate |
| | `speed_scale` | x | Multiplies terminal speed |
| | `snow_speed_ms` | m/s | Base snow fall speed |
| | `visual_density` | 1/m3 | Simulated particles per cubic metre (artistic budget) |
| air | `wind_ms`, `wind_dir_deg` | m/s, deg | Mean wind; 0 deg = +Y, 90 deg = +X |
| | `gust_strength`, `gust_scale_m`, `gust_speed_ms` | m/s, m, m/s | Noise gusts: amplitude, spatial size, drift speed |
| | `inertia` | x | Multiplies relaxation time tau = v_t / g (flakes > 1 follow air more slowly) |
| impact | `splash_amount`, `splash_speed`, `splash_life_min/max`, `splash_size` | 1, m/s, s, fraction | Splash droplets per impact |
| | `restitution`, `max_bounces` | 0-1, 1 | Bounce (hail, pellets); 0 = stick/recycle |
| look | `shutter_s`, `visual_scale`, `material` | s, x, `water`/`ice`/`snow` | Streak length = speed x shutter (0 = spheres) |
| atmosphere | `fog_density`, `fog_anisotropy`, `sky_mult`, `sun_mult` | 1/m, 0-1, x, x | Fog volume and sky/sun dimming |
| lightning | `lightning_per_min`, `lightning_energy` | 1/min, W | Flash rate and light power |
| dew | `dew_density_m2`, `dew_min_normal_z` | 1/m2, -1..1 | Bead density, minimum up-facing normal |
| legacy engine | `col_permeability`, `col_stickiness`, `col_damping`, `col_friction`, `legacy_drag` | | Collision modifier / Newtonian settings |
"""
(root / "docs" / "PRESETS.md").write_text(doc, encoding="utf-8")
print("wrote docs/PRESETS.md")
